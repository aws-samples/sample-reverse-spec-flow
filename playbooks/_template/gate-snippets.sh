#!/bin/bash
# =============================================================================
# gate-snippets.sh — ドメイン別の列挙コマンド（Playbook が提供 / GP-105）
# =============================================================================
#
# init.sh が spec-extraction/03-audit/gate-snippets.sh へ配置する。
# gates.sh は「独立ソースの実数」を必要とするが、その数え方はスタック依存であるため、
# コマンド本体をここに分離する（gates.sh 本体はスタック非依存に保つ: GP-9 ツール非依存）。
#
# 使い方:
#   bash gate-snippets.sh <subcommand> <source-path>
#     ep      エントリポイントの独立ソース件数を出力（数値 1 行）
#     bnd     外部境界（DB テーブル等）の独立ソース件数を出力（数値 1 行）
#     mod     モジュールの独立ソース件数を出力（数値 1 行）
#     list-ep エントリポイントの一覧を出力（差分調査用）
#
# 規約:
#   - 各サブコマンドは **数値 1 行のみ** を標準出力に出す（gates.sh がそのまま読む）
#   - 数えられない場合は "unknown" を出力して exit 0（0 を返すと「0 件」と誤解される）
#   - 検査は grep/awk/find のみ（外部ツール依存を作らない）
#
# 【重要】このスクリプト自体の正しさを検証すること（GP-6: ゲートのコマンド自体を検証する）。
#   ゲートを足したら「引っかかるべきもの」と「引っかかるべきでないもの」で 1 回試す。
#   件数が期待と桁違いなら、データを疑う前にコマンドを疑う。
# =============================================================================
set -uo pipefail

SRC="${2:-}"
[ -n "$SRC" ] && [ -d "$SRC" ] || { echo "unknown"; exit 0; }
# 【シンボリックリンクを物理パスに解決する（2026-09-21。実プロジェクトで踏んだ偽陰性）】
# 解析対象がシンボリックリンクで渡されると、**走査が黙って 0 件を返す**ことがある。
# 実測: `ep=unknown` / `bnd=0` / `mod=0`（本来 59/31/5）になり、
# **分母が空のまま `G-ENUM-SOURCE` が緑になった**——分母を空にして通す最悪の形である。
# 【原因は実装差にある】`find` は引数のリンクを辿らない。`grep -r` も**実装で違う**——
# 実測（同じ機で）: BSD grep 2.6.0 は**辿らない**／ugrep 7.8.4 は**辿る**。
# ⇒ **どの実装かに依存しないよう、入口で 1 度だけ物理パスに解決する**
# （個々の `find` に `-L` を足す形は、次に書く人が忘れる）。
# 見分け方: `ls <path>/<file>` は成功するのに `find <path> -name <file>` が無出力。
# 【`CDPATH= cd --` で呼ぶ】`cd` は `CDPATH` 経由で移動すると**移動先を標準出力に印字する**ため、
# `CDPATH` が設定された環境では代入値が 2 行になり、かつ別の場所を指す（実測: 正しく数えられる
# 入力が `unknown` になった）。`--` はパスが `-` で始まる場合の保険。
SRC="$(CDPATH= cd -- "$SRC" 2>/dev/null && pwd -P)" || { echo "unknown"; exit 0; }
[ -n "$SRC" ] || { echo "unknown"; exit 0; }

case "${1:-}" in
  ep)
    # <例: ルーティング定義 + ハンドラ宣言をリポジトリ全体で走査してユニーク件数を出す>
    echo "unknown"
    ;;
  bnd)
    # <例: ORM のエンティティ定義（アノテーション or マッピングファイル）+ DDL>
    echo "unknown"
    ;;
  mod)
    # <例: ビルド定義のモジュール宣言>
    echo "unknown"
    ;;
  list-ep)
    # <差分調査用: 一覧を出す。件数が合わないときに突合するため>
    ;;
  *)
    echo "Usage: $0 {ep|bnd|mod|list-ep} <source-path>" >&2
    exit 2
    ;;
esac
